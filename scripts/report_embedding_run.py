"""Markdown report of one dense baseline run, from its summary.json.

    PYTHONPATH=. .venv/bin/python scripts/report_embedding_run.py \\
        data/results/dev-0.10.0/multilingual-e5-large-layer-500/summary.json

The report is versioned, so it never carries a Spanish query: those are named by id
and live only in data/benchmark/dev/queries.jsonl.
"""

from __future__ import annotations

import json
import sys
from collections.abc import Mapping, Sequence
from pathlib import Path
from typing import Any

METRICS = [
    "nDCG@10",
    "Recall@10",
    "MRR@10",
    "Recall@5",
    "Recall@20",
    "Recall@T=1000",
    "Recall@T=2000",
]


def table(header: Sequence[str], rows: Sequence[Sequence[Any]]) -> list[str]:
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return out


def f3(x: float) -> str:
    return f"{x:.3f}"


def metric_rows(groups: Mapping[str, Mapping[str, Any]], label: str = "") -> list[list[Any]]:
    rows = []
    for name, g in groups.items():
        mark = " (descriptive)" if g.get("descriptive_only") else ""
        rows.append([f"{label}{name}{mark}", g["needs"], *[f3(g[m]) for m in METRICS]])
    return rows


def main(path: Path) -> int:
    s = json.loads(path.read_text(encoding="utf-8"))
    m, ex, model, lay = s["metrics"], s["exposure"], s["model"], s["layer"]
    dt, name = ex["dropped_tokens"], model["name"]
    backend = s["identity"]["runtime"] | s["performance"]["environment"]
    config_link = f"[`config/embeddings/{name}.json`](../../../../config/embeddings/{name}.json)"
    exposed_needs = ex["needs_with_a_truncated_relevant_chunk"]
    tok = s["tokenization"]
    td, tq = tok["documents"], tok["queries"]
    lines = [
        f"# Dense baseline: {model['model_id']} on DEV {s['benchmark_version']}, "
        f"layer {lay['max_tokens']}",
        "",
        "Generated by `scripts/embed_baseline.py` and `scripts/report_embedding_run.py`. The "
        "numbers come from the official evaluator (`ingest/evaluation.py`); no benchmark label "
        "was changed or read for anything but scoring.",
        "",
        "## Provenance",
        "",
        f"- Model `{model['model_id']}` at revision `{model['revision']}`, contract SHA-256 "
        f"`{s['config_hash'][:16]}…` ({config_link}).",
        f"- DEV {s['benchmark_version']} (protocol v1.4), parser {s['parser_version']}, "
        f"queries.jsonl SHA-256 `{s['queries_sha256'][:16]}…`.",
        f"- Chunk layer: {lay['max_tokens']} `{lay['chunk_tokenizer']}` tokens, chunker "
        f"{lay['chunker_version']}, content SHA-256 `{lay['content_sha256'][:16]}…`.",
        f"- Backend: {', '.join(f'{k} {v}' for k, v in backend.items())}.",
        "- Search: exact, one dot product per query and chunk. With L2-normalized vectors the dot "
        "product is the cosine similarity.",
        "",
        "## Tokenization and truncation exposure",
        "",
        f"Model tokens per chunk, counted with the model's own tokenizer on the exact input "
        f"(prefix and special tokens included): min {td['min']}, median {td['median']}, p95 "
        f"{td['p95']}, p99 {td['p99']}, max {td['max']}; {td['over_limit']} over the limit of "
        f"{tok['limit']}. Queries: min {tq['min']}, median {tq['median']}, max {tq['max']}; "
        f"{tq['over_limit']} over the limit (a query over it is refused, never cut).",
        "",
        f"{ex['truncated_chunks']} of {ex['total_chunks']} chunks "
        f"({100 * ex['truncated_share']:.1f}%) exceed the model's {model['max_input_tokens']} "
        f"input tokens and are cut at the tail, explicitly. Dropped tokens among them: min "
        f"{dt['min']}, median {dt['median']}, p95 {dt['p95']}, max {dt['max']}. By act: "
        f"{', '.join(f'{k} {v}' for k, v in ex['by_act'].items())}.",
        "",
        "Needs with a truncated relevant chunk: "
        + ", ".join(f"{n} ({', '.join(c)})" for n, c in exposed_needs.items())
        + ".",
        "",
    ]
    cut = ex["judged_nodes_in_truncated_text"]
    lines += table(
        ["Need", "Node", "Grade", "In the truncated text", "Chunk"],
        [
            [n["need"], n["node"], n["grade"], n["state"], n["chunk"]]
            for n in cut["relevant"] + cut["grade_1"] + cut["grade_0"]
        ],
    )
    lines += [
        "",
        "Exposure is not a cause: a failure is called truncation-exposed when a truncated "
        "chunk is among the need's relevant chunks or the top 10, and nothing more is claimed.",
        "",
        "## Metrics",
        "",
        "Official aggregation (D-020): per need first, then per language; English and Spanish "
        "are never mixed.",
        "",
    ]
    lines += table(["Language", "Needs", *METRICS], metric_rows(m["official_by_language"]))
    lines += ["", "By query style (one query per need and style):", ""]
    lines += table(["Style", "Needs", *METRICS], metric_rows(m["by_style"]))
    lines += [
        "",
        "Macro by need (all three queries of each need, then over needs). It mixes languages, "
        "so it is a descriptive summary, not an official number.",
        "",
    ]
    lines += table(["", "Needs", *METRICS], metric_rows({"all styles": m["macro_by_need"]}))
    lines += [
        "",
        "### By type, difficulty, answerability and driver",
        "",
        "Macro by need. Groups under 5 needs are marked descriptive.",
        "",
    ]
    for key in ("by_type", "by_difficulty", "by_answerability", "by_driver"):
        lines += table(
            [key.replace("by_", "").capitalize(), "Needs", *METRICS], metric_rows(m[key])
        )
        lines.append("")
    lines += [
        "### Spanish against English",
        "",
        "Paired per need, bootstrap 95% interval over needs (seed 20261013).",
        "",
    ]
    rows = []
    for metric, comparisons in m["language_effect"].items():
        for name, d in comparisons.items():
            rows.append(
                [
                    metric,
                    name.replace("_", " "),
                    f"{d['mean']:+.3f}",
                    f"[{d['ci95_low']:+.3f}, {d['ci95_high']:+.3f}]",
                    d["es_better"],
                    d["en_better"],
                    d["equal"],
                ]
            )
    lines += table(
        ["Metric", "Difference", "Mean", "95% interval", "ES better", "EN better", "Equal"], rows
    )
    lines += [
        "",
        "## Per need",
        "",
        "Means over the three queries. First relevant rank per query: EN formal / EN natural "
        "/ ES natural.",
        "",
    ]
    rows = []
    for n in s["per_need"]:
        fr = n["first_relevant_rank"]
        rows.append(
            [
                n["need"],
                n["type"],
                n["difficulty"],
                n["answerability"],
                " ".join(n["drivers"]) or "none",
                n["relevant_chunks"],
                f"{f3(n['Recall@5'])} (max {f3(n['recall5_ceiling'])})",
                f3(n["Recall@10"]),
                f3(n["nDCG@10"]),
                f"{fr['en formal']} / {fr['en natural']} / {fr['es natural']}",
                ", ".join(n["flags"]),
            ]
        )
    lines += table(
        [
            "Need",
            "Type",
            "Difficulty",
            "Answerability",
            "Drivers",
            "Rel. chunks",
            "Recall@5",
            "Recall@10",
            "nDCG@10",
            "First relevant",
            "Flags",
        ],
        rows,
    )
    lines += [
        "",
        "### Where the relevant chunks rank, for the needs with Recall@10 under 1",
        "",
        "Rank of every relevant chunk in each query's exact ranking (truncated chunks marked *).",
        "",
    ]
    truncated = {c["chunk"] for c in ex["chunks"]}
    rows = []
    for n in s["per_need"]:
        if "Recall@10<1" not in n["flags"]:
            continue
        for qid, q in sorted(s["per_query"].items()):
            if qid.startswith(n["need"] + "-"):
                ranks = sorted(q["relevant_ranks"].items(), key=lambda x: x[1])
                cells = ", ".join(f"{c}{'*' if c in truncated else ''} {r}" for c, r in ranks)
                rows.append([n["need"], qid, cells])
    lines += table(["Need", "Query", "Relevant chunks and their ranks"], rows)
    lines += [
        "",
        "## Failure analysis",
        "",
        "The queries with the lowest nDCG@10. Spanish queries are named by id.",
        "",
    ]
    for f in s["failures"]:
        text = f["text"] if f["text"] else f"(Spanish query {f['query_id']})"
        lines += [
            f"### {f['query_id']} ({f['need']}, {f['lang']} {f['style']})",
            "",
            f"Query: {text}",
            "",
            f"nDCG@10 {f3(f['values']['nDCG@10'])}, Recall@10 {f3(f['values']['Recall@10'])}, "
            f"first relevant rank {f['first_relevant_rank']}"
            f"{', truncation-exposed' if f['truncation_exposed'] else ''}.",
            "",
        ]
        lines += table(
            ["Rank", "Chunk", "Score", "Grade", "Relevant", "Preview"],
            [
                [
                    t["rank"],
                    t["chunk"] + (" (truncated)" if t["truncated"] else ""),
                    f"{t['score']:.4f}",
                    "unjudged" if t["grade"] is None else t["grade"],
                    "yes" if t["relevant"] else "no",
                    t["preview"][:100].replace("|", "/"),
                ]
                for t in f["top10"]
            ],
        )
        lines += [
            "",
            "Relevant chunks: "
            + ", ".join(
                f"{r['chunk']} (rank {r['rank']}, grade {r['grade']}"
                f"{', truncated' if r['truncated'] else ''})"
                for r in f["relevant_chunks"]
            ),
            "",
        ]
    p = s["performance"]
    size = p["embedding_bytes"]
    lines += ["## Sanity checks", ""] + [f"- {k}: {v}" for k, v in s["sanity"].items()]
    lines += [
        "",
        "## Performance",
        "",
        f"- {p['documents']} documents and {p['queries']} queries, {p['dimension']} dimensions.",
        "- Times (seconds): "
        + ", ".join(f"{k} {v:.1f}" for k, v in p["timings_seconds"].items())
        + ".",
        f"- Stored: documents {size['documents'] / 1e6:.2f} MB (+ meta "
        f"{size['documents_meta'] / 1e6:.2f} MB), queries {size['queries'] / 1e6:.2f} MB.",
        f"- Peak resident memory of the process: {p['peak_rss_bytes'] / 1e9:.2f} GB.",
        f"- Model files in the Hugging Face cache: {p['model_cache_bytes'] / 1e9:.2f} GB.",
        "",
    ]
    out = path.with_name("report.md")
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"written {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main(Path(sys.argv[1])))
